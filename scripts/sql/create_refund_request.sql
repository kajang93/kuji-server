-- 환불 요청 원본과 검토 이력을 보관하며 실제 결제 취소는 실행하지 않습니다.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '15s';
CREATE TABLE IF NOT EXISTS refund_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member(id),
    target_type VARCHAR(20) NOT NULL CHECK (target_type IN ('DRAW_HISTORY', 'POINT_CHARGE')),
    target_id BIGINT NOT NULL CHECK (target_id > 0),
    title VARCHAR(300) NOT NULL,
    source_occurred_at TIMESTAMP,
    target_amount BIGINT CHECK (target_amount IS NULL OR target_amount > 0),
    fulfillment_status VARCHAR(30) NOT NULL,
    reason VARCHAR(1000) NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 10 AND 1000),
    status VARCHAR(24) NOT NULL CHECK (status IN ('REQUESTED', 'UNDER_REVIEW', 'REVIEW_APPROVED', 'REJECTED')),
    active_target_key VARCHAR(80),
    review_reason VARCHAR(1000),
    reviewed_at TIMESTAMP,
    reviewed_by BIGINT REFERENCES member(id),
    created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_refund_request_active_target UNIQUE (active_target_key),
    CONSTRAINT ck_refund_request_active_key CHECK (
        (status = 'REJECTED' AND active_target_key IS NULL) OR
        (status <> 'REJECTED' AND active_target_key IS NOT NULL AND active_target_key = target_type || ':' || target_id::text)),
    CONSTRAINT ck_refund_request_review CHECK (
        (status = 'REQUESTED' AND review_reason IS NULL AND reviewed_at IS NULL AND reviewed_by IS NULL) OR
        (status <> 'REQUESTED' AND review_reason IS NOT NULL AND char_length(btrim(review_reason)) BETWEEN 5 AND 1000 AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL)),
    CONSTRAINT ck_refund_request_amount CHECK (target_type <> 'DRAW_HISTORY' OR target_amount IS NULL)
);
CREATE INDEX IF NOT EXISTS idx_refund_request_member_created ON refund_request(member_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_refund_request_status_created ON refund_request(status, created_at DESC);
CREATE TABLE IF NOT EXISTS refund_review (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_request_id BIGINT NOT NULL REFERENCES refund_request(id),
    from_status VARCHAR(24) NOT NULL,
    to_status VARCHAR(24) NOT NULL,
    reviewer_id BIGINT NOT NULL REFERENCES member(id),
    reason VARCHAR(1000) NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 5 AND 1000),
    created_at TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT ck_refund_review_transition CHECK (
        (from_status = 'REQUESTED' AND to_status = 'UNDER_REVIEW') OR
        (from_status = 'UNDER_REVIEW' AND to_status IN ('REVIEW_APPROVED', 'REJECTED')))
);
CREATE INDEX IF NOT EXISTS idx_refund_review_request ON refund_review(refund_request_id, id);
COMMIT;
