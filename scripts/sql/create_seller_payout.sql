-- 실제 은행 송금 확인 뒤 관리자가 기록한 지급과 전체 매출 원장의 배분을 변경 불가로 보관합니다.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '15s';
CREATE TABLE IF NOT EXISTS seller_payout (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES member(id),
    amount BIGINT NOT NULL CHECK (amount > 0),
    paid_date DATE NOT NULL,
    transfer_reference VARCHAR(200) NOT NULL CHECK (char_length(btrim(transfer_reference)) BETWEEN 1 AND 200),
    evidence_reference VARCHAR(500) NOT NULL CHECK (char_length(btrim(evidence_reference)) BETWEEN 1 AND 500),
    request_id UUID NOT NULL UNIQUE,
    request_fingerprint VARCHAR(64) NOT NULL CHECK (char_length(request_fingerprint) = 64),
    recorded_by BIGINT NOT NULL REFERENCES member(id),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_seller_payout_seller_recorded ON seller_payout(seller_id,recorded_at DESC,id DESC);
CREATE TABLE IF NOT EXISTS seller_payout_allocation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payout_id BIGINT NOT NULL REFERENCES seller_payout(id),
    sale_id BIGINT NOT NULL UNIQUE REFERENCES seller_sale(id),
    amount BIGINT NOT NULL CHECK (amount > 0)
);
CREATE INDEX IF NOT EXISTS idx_seller_payout_allocation_payout ON seller_payout_allocation(payout_id);

CREATE OR REPLACE FUNCTION seller_payout_reject_change() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '지급 기록과 원장 배분은 수정하거나 삭제할 수 없습니다.';
END;
$$;
DROP TRIGGER IF EXISTS seller_payout_immutable ON seller_payout;
CREATE TRIGGER seller_payout_immutable BEFORE UPDATE OR DELETE ON seller_payout
    FOR EACH ROW EXECUTE FUNCTION seller_payout_reject_change();
DROP TRIGGER IF EXISTS seller_payout_allocation_immutable ON seller_payout_allocation;
CREATE TRIGGER seller_payout_allocation_immutable BEFORE UPDATE OR DELETE ON seller_payout_allocation
    FOR EACH ROW EXECUTE FUNCTION seller_payout_reject_change();

CREATE OR REPLACE FUNCTION seller_payout_validate_allocation() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    sale_seller BIGINT;
    sale_net BIGINT;
    sale_environment VARCHAR(10);
    payout_seller BIGINT;
BEGIN
    SELECT seller_id,net_amount,payment_environment INTO sale_seller,sale_net,sale_environment FROM seller_sale WHERE id=NEW.sale_id;
    SELECT seller_id INTO payout_seller FROM seller_payout WHERE id=NEW.payout_id;
    IF sale_seller IS NULL OR payout_seller IS NULL OR sale_seller <> payout_seller
            OR sale_environment <> 'LIVE' OR NEW.amount <> sale_net THEN
        RAISE EXCEPTION '동일 판매자의 실제 거래 원장 전체 금액만 배분할 수 있습니다.';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS seller_payout_allocation_valid ON seller_payout_allocation;
CREATE TRIGGER seller_payout_allocation_valid BEFORE INSERT ON seller_payout_allocation
    FOR EACH ROW EXECUTE FUNCTION seller_payout_validate_allocation();

CREATE OR REPLACE FUNCTION seller_payout_check_balance() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.amount <> (SELECT COALESCE(SUM(amount),0) FROM seller_payout_allocation WHERE payout_id=NEW.id) THEN
        RAISE EXCEPTION '지급액과 원장 배분 합계가 일치하지 않습니다.';
    END IF;
    RETURN NULL;
END;
$$;
DROP TRIGGER IF EXISTS seller_payout_balanced ON seller_payout;
CREATE CONSTRAINT TRIGGER seller_payout_balanced AFTER INSERT ON seller_payout
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION seller_payout_check_balance();
-- 이미 존재하는 지급 헤더에도 새 배분을 추가해 합계를 바꾸지 못하도록 확인합니다.
CREATE OR REPLACE FUNCTION seller_payout_check_allocation_balance() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT amount FROM seller_payout WHERE id=NEW.payout_id)
            <> (SELECT COALESCE(SUM(amount),0) FROM seller_payout_allocation WHERE payout_id=NEW.payout_id) THEN
        RAISE EXCEPTION '지급액과 원장 배분 합계가 일치하지 않습니다.';
    END IF;
    RETURN NULL;
END;
$$;
DROP TRIGGER IF EXISTS seller_payout_allocation_balanced ON seller_payout_allocation;
CREATE CONSTRAINT TRIGGER seller_payout_allocation_balanced AFTER INSERT ON seller_payout_allocation
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION seller_payout_check_allocation_balance();
COMMIT;
