-- 실제 구매대금과 거래 당시 수수료 및 전체 당첨 연결을 변경 불가 원장으로 보관합니다.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '15s';
CREATE TABLE IF NOT EXISTS seller_sale (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL REFERENCES member(id),
    seller_id BIGINT NOT NULL REFERENCES member(id),
    board_id BIGINT NOT NULL REFERENCES kujiboard(id),
    payment_id BIGINT REFERENCES payment(id),
    source_key VARCHAR(180) NOT NULL,
    payment_environment VARCHAR(10) NOT NULL DEFAULT 'UNKNOWN' CONSTRAINT ck_seller_sale_environment CHECK (payment_environment IN ('TEST', 'LIVE', 'UNKNOWN')),
    purchased_count INTEGER NOT NULL CHECK (purchased_count > 0),
    gross_amount BIGINT NOT NULL CHECK (gross_amount > 0),
    pg_amount BIGINT NOT NULL CHECK (pg_amount >= 0),
    point_amount BIGINT NOT NULL CHECK (point_amount >= 0),
    applied_fee_rate INTEGER NOT NULL CHECK (applied_fee_rate BETWEEN 0 AND 100),
    fee_amount BIGINT NOT NULL CHECK (fee_amount >= 0),
    net_amount BIGINT NOT NULL CHECK (net_amount >= 0),
    completed_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_seller_sale_source UNIQUE(source_key),
    CONSTRAINT uq_seller_sale_payment UNIQUE(payment_id),
    CONSTRAINT ck_seller_sale_money CHECK (gross_amount = pg_amount + point_amount AND fee_amount = gross_amount * applied_fee_rate / 100 AND net_amount = gross_amount - fee_amount),
    CONSTRAINT ck_seller_sale_source CHECK ((payment_id IS NULL AND pg_amount = 0 AND source_key LIKE 'POINT:%') OR (payment_id IS NOT NULL AND pg_amount > 0 AND source_key LIKE 'PG:%'))
);
-- 기존 원장의 결제 환경을 임의로 실제 거래로 소급하지 않습니다.
ALTER TABLE seller_sale ADD COLUMN IF NOT EXISTS payment_environment VARCHAR(10) NOT NULL DEFAULT 'UNKNOWN'
    CONSTRAINT ck_seller_sale_environment CHECK (payment_environment IN ('TEST', 'LIVE', 'UNKNOWN'));
CREATE INDEX IF NOT EXISTS idx_seller_sale_seller_completed ON seller_sale(seller_id,completed_at);
CREATE TABLE IF NOT EXISTS seller_sale_draw (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES seller_sale(id),
    draw_history_id BIGINT NOT NULL REFERENCES drawhistory(id),
    CONSTRAINT uq_seller_sale_draw_history UNIQUE(draw_history_id)
);
CREATE INDEX IF NOT EXISTS idx_seller_sale_draw_sale ON seller_sale_draw(sale_id);
COMMIT;
