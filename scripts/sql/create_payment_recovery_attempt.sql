-- 결제 승인 전 복구 기록을 보관하며 새 애플리케이션 배포 전에 한 번 적용한다.
BEGIN;
ALTER TABLE payment ALTER COLUMN pguid TYPE varchar(200);
CREATE TABLE IF NOT EXISTS payment_recovery_attempt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id varchar(100) NOT NULL UNIQUE REFERENCES paymentsession(order_id),
    member_id bigint NOT NULL REFERENCES member(id),
    payment_key varchar(200) NOT NULL UNIQUE,
    amount integer NOT NULL CHECK (amount > 0),
    session_type varchar(20) NOT NULL CHECK (session_type IN ('KUJI_DRAW', 'POINT_CHARGE')),
    state varchar(20) NOT NULL CHECK (state IN ('OPEN', 'SUBMITTING', 'RECOVERING', 'COMPLETED', 'CANCELLED', 'FAILED')),
    result_json text,
    retry_at timestamp NOT NULL,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_payment_recovery_due ON payment_recovery_attempt (retry_at) WHERE state IN ('OPEN', 'SUBMITTING', 'RECOVERING');
COMMIT;
